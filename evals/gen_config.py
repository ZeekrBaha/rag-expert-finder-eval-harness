"""Generate promptfooconfig.yaml with ONLY the providers whose API keys are set.

Run only what you can pay for: with just OPENAI_API_KEY the suite runs the openai
candidate; add ANTHROPIC_API_KEY / DEEPSEEK_API_KEY and they auto-join the A/B.
select_providers() is pure + tested; main() writes the YAML.
"""
import sys

from app.config import Settings

# label shown in the report  ->  (env-key attribute, provider arg for provider.py)
_CANDIDATES = [
    ("gpt-4o-mini", "openai_api_key", "openai"),
    ("claude", "anthropic_api_key", "anthropic"),
    ("deepseek", "deepseek_api_key", "deepseek"),
]


def select_providers(settings: Settings) -> list[dict]:
    """Return [{label, model_provider}] for every candidate whose key is present."""
    out = []
    for label, attr, provider in _CANDIDATES:
        if getattr(settings, attr):
            out.append({"label": label, "model_provider": provider})
    return out


def render_yaml(providers: list[dict], judge_model: str, rubric_text: str,
                variant: str = "good") -> str:
    lines = [
        "# AUTO-GENERATED by evals/gen_config.py — edits will be overwritten.",
        "# Only providers with a configured API key are included.",
        "description: RAG expert-finder eval — qualify the right PI, catch confident-wrong matches.",
        "",
        "providers:",
    ]
    for p in providers:
        lines += [
            "  - id: file://provider.py",
            f"    label: {p['label']}",
            f"    config: {{ model_provider: {p['model_provider']}, "
            f"prompt_variant: {variant} }}",
        ]
    lines += [
        "",
        "defaultTest:",
        "  assert:",
        "    - type: llm-rubric",
        "      # Judge shares the GPT-4o family with the gpt-4o-mini candidate; a fully",
        "      # out-of-family judge isn't available with these 3 vendors. Residual",
        "      # affinity is acknowledged and quantified via the bias probe. Override",
        "      # with JUDGE_MODEL to point at a 4th-family judge.",
        f"      provider: {judge_model}",
        "      # Rubric inlined (this Promptfoo version rejects file://*.md as a value).",
        "      value: |",
    ]
    # Inline the rubric as an indented YAML block scalar (8 spaces under `value: |`).
    for rline in rubric_text.splitlines():
        lines.append("        " + rline if rline else "")
    lines += [
        "",
        "tests: file://tests.json",
        "",
    ]
    return "\n".join(lines)


def main(out_path: str = "evals/promptfooconfig.yaml",
         rubric_path: str = "evals/graders/judge_rubric.md",
         regression_out_path: str = "evals/promptfooconfig.regression.yaml") -> None:
    s = Settings.from_env()
    providers = select_providers(s)
    if not providers:
        print("ERROR: no provider keys set — nothing to run.", file=sys.stderr)
        raise SystemExit(1)
    judge = s.judge_model if ":" in s.judge_model else "openai:gpt-4o"
    rubric_text = open(rubric_path, encoding="utf-8").read()
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(render_yaml(providers, judge, rubric_text, variant="good"))
    with open(regression_out_path, "w", encoding="utf-8") as f:
        f.write(render_yaml(providers, judge, rubric_text, variant="regression"))
    labels = ", ".join(p["label"] for p in providers)
    print(f"wrote {out_path} with {len(providers)} provider(s): {labels}")
    print(f"wrote {regression_out_path} (regression variant) with "
          f"{len(providers)} provider(s): {labels}")


if __name__ == "__main__":  # pragma: no cover
    main(*sys.argv[1:])
